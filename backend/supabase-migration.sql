-- 修正历史遗留表结构 + 补齐 products / orders 两张表
-- + 索引 + 统计函数 + 种子商品
--
-- 执行方式：Supabase Dashboard → 左侧 SQL Editor → New query
--           → 全文粘贴 → Run（或 Ctrl+Enter）
