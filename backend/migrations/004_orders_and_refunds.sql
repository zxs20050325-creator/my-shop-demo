UPDATE orders o
   SET user_id = u.id
  FROM users u
 WHERE o.user_id IS NULL
   AND o.username = u.username;

UPDATE orders
   SET goods_amount_cents = GREATEST(ROUND(COALESCE(total, 0) * 100)::BIGINT, 0),
       payable_amount_cents = GREATEST(ROUND(COALESCE(total, 0) * 100)::BIGINT, 0),
       paid_amount_cents = CASE
           WHEN status IN ('待发货', '已发货', '已完成') THEN GREATEST(ROUND(COALESCE(total, 0) * 100)::BIGINT, 0)
           ELSE 0
       END,
       payment_status = CASE
           WHEN status IN ('待发货', '已发货', '已完成') THEN 'paid'
           ELSE 'unpaid'
       END
 WHERE goods_amount_cents = 0
   AND payable_amount_cents = 0;

UPDATE orders
   SET status = '待发货'
 WHERE status IS NULL
    OR status NOT IN ('待付款', '待发货', '已发货', '已完成', '已取消');

