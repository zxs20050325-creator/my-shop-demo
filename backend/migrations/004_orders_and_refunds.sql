UPDATE order_items
   SET product_name = COALESCE(NULLIF(product_name, ''), name, '未知商品'),
       product_img = COALESCE(NULLIF(product_img, ''), img, ''),
       price_cents = CASE
           WHEN price_cents = 0 THEN GREATEST(ROUND(COALESCE(price, 0) * 100)::BIGINT, 0)
           ELSE price_cents
       END,
       subtotal_cents = CASE
           WHEN subtotal_cents = 0 THEN GREATEST(ROUND(COALESCE(price, 0) * 100)::BIGINT * COALESCE(quantity, 1), 0)
           ELSE subtotal_cents
       END;

CREATE TABLE IF NOT EXISTS order_status_logs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    from_status    TEXT,
    to_status      TEXT NOT NULL,
    operator_id    BIGINT,
    operator_role  TEXT NOT NULL DEFAULT 'system',
    remark         TEXT NOT NULL DEFAULT '',
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS refund_requests (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id       BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason         TEXT NOT NULL,
    amount_cents   BIGINT NOT NULL DEFAULT 0,
    status         TEXT NOT NULL DEFAULT '待处理',
    admin_note     TEXT NOT NULL DEFAULT '',
    handled_by     BIGINT REFERENCES users(id),
    applied_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    handled_at     TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT refund_requests_status_check CHECK (status IN ('待处理', '已同意', '已拒绝', '已撤销'))
);

CREATE TABLE IF NOT EXISTS payment_records (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    method           TEXT NOT NULL,
    amount_cents     BIGINT NOT NULL,
    transaction_no   TEXT NOT NULL UNIQUE,
    status           TEXT NOT NULL DEFAULT 'success',
    paid_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT payment_records_status_check CHECK (status IN ('success', 'refunded', 'failed'))
);

