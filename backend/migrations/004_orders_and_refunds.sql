    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'orders_payment_status_check_v2') THEN
        ALTER TABLE orders ADD CONSTRAINT orders_payment_status_check_v2
        CHECK (payment_status IN ('unpaid', 'paid', 'refund_requested', 'refunded', 'refund_rejected'));
    END IF;
END $$;

