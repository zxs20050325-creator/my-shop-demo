CREATE TABLE IF NOT EXISTS product_options (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (product_id, name)
);

CREATE TABLE IF NOT EXISTS product_option_values (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    option_id   BIGINT NOT NULL REFERENCES product_options(id) ON DELETE CASCADE,
    value       TEXT NOT NULL,
    sort_order  INTEGER NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (option_id, value)
);

CREATE TABLE IF NOT EXISTS product_skus (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id     BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    sku_code       TEXT NOT NULL UNIQUE,
    spec_values    JSONB NOT NULL DEFAULT '{}'::jsonb,
    spec_text      TEXT NOT NULL DEFAULT '默认规格',
    price_cents    BIGINT NOT NULL DEFAULT 0,
    stock          INTEGER NOT NULL DEFAULT 0,
    locked_stock   INTEGER NOT NULL DEFAULT 0,
    active         INTEGER NOT NULL DEFAULT 1,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT product_skus_price_check CHECK (price_cents >= 0),
    CONSTRAINT product_skus_stock_check CHECK (stock >= 0),
    CONSTRAINT product_skus_locked_check CHECK (locked_stock >= 0),
    CONSTRAINT product_skus_active_check CHECK (active IN (0, 1))
);

CREATE TABLE IF NOT EXISTS product_sku_option_values (
    sku_id           BIGINT NOT NULL REFERENCES product_skus(id) ON DELETE CASCADE,
    option_value_id  BIGINT NOT NULL REFERENCES product_option_values(id) ON DELETE CASCADE,
    PRIMARY KEY (sku_id, option_value_id)
);

CREATE TABLE IF NOT EXISTS inventory_logs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_id            BIGINT NOT NULL REFERENCES product_skus(id),
    order_id          BIGINT,
    change_quantity   INTEGER NOT NULL,
    before_stock      INTEGER NOT NULL,
    after_stock       INTEGER NOT NULL,
    reason            TEXT NOT NULL,
    operator_id       BIGINT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_products_category_status ON products(category_id, status);
CREATE INDEX IF NOT EXISTS idx_product_skus_product ON product_skus(product_id, active);
CREATE INDEX IF NOT EXISTS idx_inventory_logs_sku ON inventory_logs(sku_id, created_at DESC);

INSERT INTO product_skus (product_id, sku_code, spec_values, spec_text, price_cents, stock, active)
SELECT p.id,
       'P' || p.id || '-DEFAULT',
       '{}'::jsonb,
       '默认规格',
       GREATEST(ROUND(COALESCE(p.price, 0) * 100)::BIGINT, 0),
       100,
       CASE WHEN COALESCE(p.active, 1) = 1 THEN 1 ELSE 0 END
  FROM products p
 WHERE NOT EXISTS (
       SELECT 1 FROM product_skus s WHERE s.product_id = p.id
 );

